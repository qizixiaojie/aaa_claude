-- ----------------------------------------------------------------
-- 排班（2026-08-11 ~ 2026-08-17 连续 7 天）
-- 每个医生每天 1-2 个时段：上午必出，下午按规律轮换
-- total_slots 均 20；remaining_slots 8-20 不等，部分时段余号少以体现紧张
-- ----------------------------------------------------------------
INSERT INTO schedules (doctor_id, work_date, period, total_slots, remaining_slots)
SELECT d.id,
       c.work_date,
       c.period,
       20 AS total_slots,
       20 - ((d.id + c.day_num * 2 + c.period_num * 3) % 13) AS remaining_slots
FROM doctors d
CROSS JOIN (
    SELECT DATE('2026-08-11') AS work_date, 1 AS day_num, '上午' AS period, 1 AS period_num
    UNION ALL SELECT DATE('2026-08-11'), 1, '下午', 2
    UNION ALL SELECT DATE('2026-08-12'), 2, '上午', 1
    UNION ALL SELECT DATE('2026-08-12'), 2, '下午', 2
    UNION ALL SELECT DATE('2026-08-13'), 3, '上午', 1
    UNION ALL SELECT DATE('2026-08-13'), 3, '下午', 2
    UNION ALL SELECT DATE('2026-08-14'), 4, '上午', 1
    UNION ALL SELECT DATE('2026-08-14'), 4, '下午', 2
    UNION ALL SELECT DATE('2026-08-15'), 5, '上午', 1
    UNION ALL SELECT DATE('2026-08-15'), 5, '下午', 2
    UNION ALL SELECT DATE('2026-08-16'), 6, '上午', 1
    UNION ALL SELECT DATE('2026-08-16'), 6, '下午', 2
    UNION ALL SELECT DATE('2026-08-17'), 7, '上午', 1
    UNION ALL SELECT DATE('2026-08-17'), 7, '下午', 2
) c
WHERE (d.id + c.day_num) % 3 <> 0 OR c.period_num = 1;

